def compiled_manuscript_tex(source: str, reviewer_sections: str) -> str:
    package_line = r"\usepackage{amsmath,amssymb,amsthm,booktabs,graphicx,hyperref,listings,xcolor}"
    replacement = package_line + "\n" + r"\usepackage{pgfplots}" + "\n" + r"\pgfplotsset{compat=1.18}"
    if package_line not in source:
        raise RuntimeError("expected manuscript package line was not found")
    source = source.replace(package_line, replacement, 1)

    result3_marker = r"\subsection{Result 3: failure architecture determines trustworthy refinement}"
    quotient_figure = r"""
\begin{figure}[ht]
\centering
\input{generated/paper_b_target_safe_quotient.tex}
\caption{Three levels of latent-state resolution for a five-world witness. The current record cannot separate the $A$ worlds or the $B$ worlds. Target-safe refinement splits only the classes needed to preserve the declared target under treatment; full latent identity additionally separates $A_0$ from $A_1$ although that distinction changes neither target nor declared successor.}
\label{fig:target-safe-quotient}
\end{figure}

"""
    if result3_marker not in source:
        raise RuntimeError("Result 3 insertion marker was not found")
    source = source.replace(result3_marker, quotient_figure + result3_marker, 1)

    result4_marker = r"\subsection{Result 4: adaptive risk-limited target resolution}"
    failure_figure = r"""
\begin{figure}[ht]
\centering
\input{generated/paper_b_failure_architecture.tex}
\caption{Equal nominal effort can provide different certified evidence under different failure architectures. Both designs use 30 reads across three coordinates with sensitivity lower bound 0.6 and mode-availability lower bound 0.8. The plotted triangles are worst-case guarantee ceilings implied by the lower-bound contract, not universal upper bounds on realized detection when actual availability is higher.}
\label{fig:failure-architecture}
\end{figure}

"""
    if result4_marker not in source:
        raise RuntimeError("Result 4 insertion marker was not found")
    source = source.replace(result4_marker, failure_figure + result4_marker, 1)

    figure_marker = r"\subsection{Additional dimensions}"
    figures = r"""
\begin{figure}[ht]
\centering
\input{generated/paper_b_experiment_contrast.tex}
\caption{Full-world information gain and prediction-target resolution rank the two follow-up experiments in opposite order.}
\label{fig:experiment-contrast}
\end{figure}

\begin{figure}[ht]
\centering
\input{generated/paper_b_strategy_outcomes.tex}
\caption{Terminal-report probabilities under the validated baseline. Target-safe design resolves the prediction while full-world information gain retains ambiguity after measuring the target-irrelevant attribute.}
\label{fig:strategy-outcomes}
\end{figure}

"""
    if figure_marker not in source:
        raise RuntimeError("benchmark insertion marker was not found")
    source = source.replace(figure_marker, figures + figure_marker, 1)
    discussion_marker = r"\section{Discussion}"
    if discussion_marker not in source:
        raise RuntimeError("discussion insertion marker was not found")
    source = source.replace(discussion_marker, reviewer_sections + "\n" + discussion_marker, 1)
    end_marker = r"\end{document}"
    if end_marker not in source:
        raise RuntimeError("document end marker was not found")
    return source.replace(end_marker, bibliography_tex() + "\n" + end_marker, 1)


def write_outputs() -> dict[str, object]:
    module = runpy.run_path(str(BENCHMARK))
    report = module["run_grid"]()
    if report["schema_version"] != 5:
        raise RuntimeError("figure generator requires benchmark schema version 5")
    runpy.run_path(str(ROBUSTNESS))["run"]()
    bridge_report = runpy.run_path(str(POSTERIOR_BRIDGE))["run"]()
    if bridge_report["schema_version"] != 1:
        raise RuntimeError("posterior bridge schema changed")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_CONTRAST.write_text(experiment_contrast_tex(report), encoding="utf-8")
    OUT_OUTCOMES.write_text(strategy_outcomes_tex(report), encoding="utf-8")
    OUT_QUOTIENT.write_text(target_safe_quotient_tex(), encoding="utf-8")
    OUT_FAILURE.write_text(failure_architecture_tex(), encoding="utf-8")
    source = MANUSCRIPT.read_text(encoding="utf-8")
    reviewer_sections = REVIEWER_SECTIONS.read_text(encoding="utf-8")
    COMPILED_MANUSCRIPT.write_text(
        compiled_manuscript_tex(source, reviewer_sections), encoding="utf-8"
    )
    return report


def main() -> None:
    report = write_outputs()
    print({
        "schema_version": report["schema_version"],
        "outputs": [
            str(OUT_CONTRAST.relative_to(ROOT)),
            str(OUT_OUTCOMES.relative_to(ROOT)),
            str(OUT_QUOTIENT.relative_to(ROOT)),
            str(OUT_FAILURE.relative_to(ROOT)),
            str(COMPILED_MANUSCRIPT.relative_to(ROOT)),
        ],
    })


if __name__ == "__main__":
    main()
