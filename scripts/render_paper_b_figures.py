STRATEGY_LABELS = {
    "state_only": "State-only",
    "full_identification": "Full identification",
    "full_world_eig": "Full-world EIG",
    "target_safe": "Target-safe",
}


def _fmt(value: float) -> str:
    return f"{value:.6f}"


def _baseline_rows(report: dict[str, object]) -> list[dict[str, object]]:
    rows = [
        row for row in report["rows"]
        if row["architecture"] == "independent"
        and row["state_detection_sensitivity"] == 0.95
        and row["response_typing_accuracy"] == 0.99
        and row["common_failure_probability"] == 0.0
    ]
    order = tuple(STRATEGY_LABELS)
    return sorted(rows, key=lambda row: order.index(row["strategy"]))


def experiment_contrast_tex(report: dict[str, object]) -> str:
    contrast = report["benchmark_contrast"]
    gains = contrast["full_world_information_gain_bits"]
    resolutions = contrast["target_resolution_probability"]
    return rf"""% Generated by scripts/render_paper_b_figures.py; do not edit.
\begin{{tikzpicture}}[font=\small]
  \begin{{axis}}[
    ybar, bar width=18pt, width=0.82\linewidth, height=6.2cm,
    ymin=0, ymax=2.15, ylabel={{Information or target resolution}},
    symbolic x coords={{Response experiment,Nuisance experiment}}, xtick=data,
    x tick label style={{align=center}},
    legend style={{at={{(0.5,-0.23)}},anchor=north,legend columns=2}},
    nodes near coords, nodes near coords style={{font=\scriptsize}},
  ]
    \addplot coordinates {{(Response experiment,{_fmt(gains['response'])}) (Nuisance experiment,{_fmt(gains['nuisance'])})}};
    \addplot coordinates {{(Response experiment,{_fmt(resolutions['response'])}) (Nuisance experiment,{_fmt(resolutions['nuisance'])})}};
    \legend{{Full-world information gain (bits),Target-resolution probability}}
  \end{{axis}}
\end{{tikzpicture}}
"""


def strategy_outcomes_tex(report: dict[str, object]) -> str:
    rows = _baseline_rows(report)
    coordinates = {metric: [] for metric in ("correct_probability", "wrong_probability", "ambiguity_probability")}
    for row in rows:
        label = STRATEGY_LABELS[row["strategy"]]
        for metric in coordinates:
            coordinates[metric].append(f"({{{label}}},{_fmt(row[metric])})")
    return rf"""% Generated by scripts/render_paper_b_figures.py; do not edit.
\begin{{tikzpicture}}[font=\small]
  \begin{{axis}}[
    ybar stacked, bar width=22pt, width=0.96\linewidth, height=7cm,
    ymin=0, ymax=1.02, ylabel={{Terminal-report probability}},
    symbolic x coords={{{','.join(STRATEGY_LABELS.values())}}}, xtick=data,
    x tick label style={{rotate=20,anchor=east}},
    legend style={{at={{(0.5,-0.34)}},anchor=north,legend columns=3}},
  ]
    \addplot coordinates {{{' '.join(coordinates['correct_probability'])}}};
    \addplot coordinates {{{' '.join(coordinates['wrong_probability'])}}};
    \addplot coordinates {{{' '.join(coordinates['ambiguity_probability'])}}};
    \legend{{Correct deterministic,Wrong deterministic,Honest ambiguity}}
  \end{{axis}}
\end{{tikzpicture}}
"""


def target_safe_quotient_tex() -> str:
    worlds = ("A0", "A1", "A2", "B0", "B1")
    successors = {
        "A0": "B0",
        "A1": "B0",
        "A2": "B1",
        "B0": "B0",
        "B1": "B1",
    }

    def record(world):
        return world[0]

    def target(world):
        if world == "B0":
            return "recover"
        if world == "B1":
            return "persist"
        return "pending"

    quotient = minimal_target_safe_quotient(
        worlds,
        record,
        target,
        ("treat",),
        lambda world, action: successors[world],
    )
    expected = (("A0", "A1"), ("A2",), ("B0",), ("B1",))
    if quotient.blocks != expected:
        raise RuntimeError("target-safe quotient witness changed")

    return r"""% Generated by scripts/render_paper_b_figures.py; do not edit.
\begin{tikzpicture}[x=1cm,y=1cm,font=\small]
  \node[anchor=east] at (-0.35,2.8) {Current record};
  \node[anchor=east] at (-0.35,1.4) {Target-safe quotient};
  \node[anchor=east] at (-0.35,0.0) {Full latent identity};

  % Fixed latent-world positions.
  \node at (0.35,2.8) {$A_0$}; \node at (1.15,2.8) {$A_1$}; \node at (1.95,2.8) {$A_2$};
  \node at (3.35,2.8) {$B_0$}; \node at (4.15,2.8) {$B_1$};
  \draw[rounded corners] (0.0,2.45) rectangle (2.30,3.15);
  \draw[rounded corners] (3.0,2.45) rectangle (4.50,3.15);

  \node at (0.35,1.4) {$A_0$}; \node at (1.15,1.4) {$A_1$}; \node at (1.95,1.4) {$A_2$};
  \node at (3.35,1.4) {$B_0$}; \node at (4.15,1.4) {$B_1$};
  \draw[rounded corners] (0.0,1.05) rectangle (1.50,1.75);
  \draw[rounded corners] (1.65,1.05) rectangle (2.25,1.75);
  \draw[rounded corners] (3.05,1.05) rectangle (3.65,1.75);
  \draw[rounded corners] (3.85,1.05) rectangle (4.45,1.75);

  \node at (0.35,0.0) {$A_0$}; \node at (1.15,0.0) {$A_1$}; \node at (1.95,0.0) {$A_2$};
  \node at (3.35,0.0) {$B_0$}; \node at (4.15,0.0) {$B_1$};
  \draw[rounded corners] (0.05,-0.35) rectangle (0.65,0.35);
  \draw[rounded corners] (0.85,-0.35) rectangle (1.45,0.35);
  \draw[rounded corners] (1.65,-0.35) rectangle (2.25,0.35);
  \draw[rounded corners] (3.05,-0.35) rectangle (3.65,0.35);
  \draw[rounded corners] (3.85,-0.35) rectangle (4.45,0.35);

  \draw[->] (4.95,2.42) -- node[right,align=left,font=\scriptsize] {refine only when target\\or successor differs} (4.95,1.78);
  \draw[dashed,->] (4.95,1.02) -- node[right,align=left,font=\scriptsize] {extra identity split\\not required for target} (4.95,0.38);
\end{tikzpicture}
"""


def failure_architecture_tex() -> str:
    detector = OneSidedDetector(0.6)
    one_mode = ModeDiverseDetectionPanel(3, 1, 10, 0.8, detector)
    two_modes = ModeDiverseDetectionPanel(3, 2, 5, 0.8, detector)
    if one_mode.total_reads != two_modes.total_reads or one_mode.total_reads != 30:
        raise RuntimeError("equal-effort failure witness changed")

    return rf"""% Generated by scripts/render_paper_b_figures.py; do not edit.
\begin{{tikzpicture}}[font=\small]
  \begin{{axis}}[
    ybar, bar width=24pt, width=0.82\linewidth, height=6.2cm,
    ymin=0, ymax=1.03,
    ylabel={{Certified joint-detection probability}},
    symbolic x coords={{one,two}}, xtick=data,
    xticklabels={{{{1 shared mode\\10 repeats}},{{2 independent modes\\5 repeats}}}},
    x tick label style={{align=center}},
    legend style={{at={{(0.5,-0.25)}},anchor=north,legend columns=2}},
    nodes near coords, nodes near coords style={{font=\scriptsize}},
  ]
    \addplot coordinates {{(one,{_fmt(one_mode.joint_detection_lower_bound)}) (two,{_fmt(two_modes.joint_detection_lower_bound)})}};
    \addplot[only marks,mark=triangle*,mark size=3pt] coordinates {{(one,{_fmt(one_mode.availability_ceiling)}) (two,{_fmt(two_modes.availability_ceiling)})}};
    \legend{{Finite-repeat guarantee,Worst-case guarantee ceiling}}
  \end{{axis}}
  \node[font=\scriptsize,align=center] at (4.2,-1.15) {{3 coordinates; 30 reads in each design; $a\geq0.8$, $p\geq0.6$}};
\end{{tikzpicture}}
"""


